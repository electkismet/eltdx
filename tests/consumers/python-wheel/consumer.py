"""Run against an installed wheel, outside the source checkout, in final validation.

Only the standard library and public eltdx imports are used. Wire expectations
are synthetic constants authored here, not generated by a production codec.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import shutil
import socket
import struct
import sys
import threading


CODE = "sh" + str(600_001)
OTHER = "sh" + str(600_002)


def require(value, message):
    if not value:
        raise AssertionError(message)


def exact(connection, count):
    output = bytearray()
    while len(output) < count:
        data = connection.recv(count - len(output))
        if not data:
            raise EOFError("peer closed during a fixture request")
        output.extend(data)
    return bytes(output)


def varint(value):
    sign = 0x40 if value < 0 else 0
    value = abs(value)
    output = bytearray([(value & 0x3F) | sign])
    value >>= 6
    while value:
        output[-1] |= 0x80
        output.append(value & 0x7F)
        value >>= 7
    return bytes(output)


def values(*items):
    return b"".join(varint(value) for value in items)


def directory(numbers):
    output = bytearray(struct.pack("<H", len(numbers)))
    for number in numbers:
        row = bytearray(37)
        row[:6] = number
        row[6:8] = struct.pack("<H", 100)
        row[8:12] = b"TEST"
        row[24:28] = struct.pack("<f", 1.0)
        row[28] = 2
        row[29:33] = struct.pack("<f", 10.0)
        output.extend(row)
    return bytes(output)


def quote_row(identity):
    price = 1000 if identity[1:] == CODE[2:].encode("ascii") else 2000
    return identity + b"\x01\x00" + values(price, 0, 0, 0, 0, 93000, 0, 100, 1) + \
        struct.pack("<I", 0) + values(25, 75, 0, 10, -1, 1, 5, 6)


class Fixture:
    def __init__(self):
        self.listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.listener.bind(("127.0.0.1", 0))
        self.listener.listen()
        self.listener.settimeout(0.1)
        self.host = "%s:%s" % self.listener.getsockname()
        self.stopping = threading.Event()
        self.errors = []
        self.commands = []
        self.offsets = []
        self.connections = 0
        self.disconnected = threading.Event()
        self.workers = []
        self.lock = threading.Lock()
        self.thread = threading.Thread(target=self.accept, name="wheel-consumer-listener", daemon=True)

    def __enter__(self):
        self.thread.start()
        return self

    def __exit__(self, kind, value, traceback):
        self.stopping.set()
        self.thread.join(5)
        self.listener.close()
        for worker in self.workers:
            worker.join(5)
        if kind is None:
            require(not self.thread.is_alive() and all(not worker.is_alive() for worker in self.workers),
                    "fixture worker failed to terminate")
            require(not self.errors, "fixture failures: %r" % self.errors)

    def accept(self):
        try:
            while not self.stopping.is_set():
                try:
                    connection, _ = self.listener.accept()
                except socket.timeout:
                    continue
                self.connections += 1
                worker = threading.Thread(target=self.serve, args=(connection,), daemon=True)
                self.workers.append(worker)
                worker.start()
        except BaseException as error:
            self.errors.append(repr(error))

    def serve(self, connection):
        try:
            with connection:
                connection.settimeout(5)
                while not self.stopping.is_set():
                    first = connection.recv(1)
                    if not first:
                        self.disconnected.set()
                        return
                    header = first + exact(connection, 11)
                    length, repeat, command = struct.unpack_from("<HHH", header, 6)
                    require(header[0] == 0x0C and length == repeat and length >= 2, "request frame changed")
                    data = exact(connection, length - 2)
                    with self.lock:
                        self.commands.append(command)
                    payload = self.reply(command, data)
                    size = struct.pack("<H", len(payload))
                    response = b"\xb1\xcb\x74\x00\x00" + header[1:5] + b"\x00" + \
                        struct.pack("<H", command) + size + size + payload
                    connection.sendall(response)
        except BaseException as error:
            if not self.stopping.is_set():
                self.errors.append(repr(error))

    def reply(self, command, data):
        if command == 0x000D:
            require(data == b"\x01", "handshake request changed")
            payload = bytearray(189)
            payload[1:3] = struct.pack("<H", 2026)
            payload[3:9] = bytes((17, 11, 30, 10, 0, 0))
            struct.pack_into("<I", payload, 42, 20261116)
            struct.pack_into("<I", payload, 50, 20261117)
            return payload
        if command == 0x044D:
            market = struct.unpack_from("<H", data)[0]
            offset = struct.unpack_from("<I", data, 2)[0]
            self.offsets.append((market, offset))
            return directory([CODE[2:].encode("ascii"), OTHER[2:].encode("ascii")]) if market == 1 and offset == 0 else b"\x00\x00"
        if command == 0x054C:
            require(len(data) >= 10 and (len(data) - 10) % 7 == 0, "snapshot request shape changed")
            identities = [data[index:index + 7] for index in range(10, len(data), 7)]
            require(all(identity[0] == 1 and identity[1:].decode("ascii") in (CODE[2:], OTHER[2:])
                        for identity in identities), "unexpected requested security")
            return b"\x00\x00" + struct.pack("<H", len(identities)) + b"".join(quote_row(identity) for identity in identities)
        if command == 0x000F:
            count = struct.unpack_from("<H", data)[0]
            require(len(data) == 2 + 7 * count, "capital request shape changed")
            return struct.pack("<H", count) + b"".join(
                data[index:index + 7] + b"\x00\x00" for index in range(2, len(data), 7)
            )
        if command == 0x0004:
            return bytes(10)
        raise AssertionError("unexpected command 0x%04x" % command)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--forbidden-root", type=Path, required=True)
    parser.add_argument("--require-no-toolchain", action="store_true")
    parser.add_argument("--evidence", type=Path)
    args = parser.parse_args()
    if args.require_no_toolchain:
        found = {name: shutil.which(name) for name in ("rustc", "cargo", "maturin")}
        require(not any(found.values()), "consumer environment exposes a build tool: %r" % found)
    else:
        found = None

    import eltdx
    from eltdx import TdxClient
    from eltdx.models import CapitalChangeBatch, QuoteSnapshot
    from eltdx.transport import SocketTransport

    installed = Path(eltdx.__file__).resolve()
    forbidden = args.forbidden_root.resolve()
    require(not installed.is_relative_to(forbidden), "consumer imported the source checkout instead of the installed wheel")
    require(not os.environ.get("PYTHONPATH"), "consumer requires an isolated PYTHONPATH")
    with Fixture() as fixture:
        client = TdxClient(transport=SocketTransport([fixture.host], timeout=3, heartbeat_interval=None), probe_hosts=False)
        try:
            codes = client.codes.all("sh", page_size=2)
            require([row.full_code for row in codes] == [CODE, OTHER], "nonempty directory result changed")
            requested = [CODE, OTHER, CODE]
            quotes = client.quotes.get_snapshots(requested)
            require([row.full_code for row in quotes] == requested, "snapshot order or duplicates changed")
            require(all(isinstance(row, QuoteSnapshot) for row in quotes), "public quote DTO changed")
            require([row.last_price for row in quotes] == [10.0, 20.0, 10.0], "wire price scaling changed")
            capital = client.corporate.capital_changes([CODE, OTHER], include_raw=True, batch_size=1)
            require(isinstance(capital, CapitalChangeBatch), "public capital batch DTO changed")
            require([block.full_code for block in capital.blocks] == [CODE, OTHER], "capital chunk assembly changed")
            require(len(capital.raw_payloads) == 2 and all(capital.raw_payloads), "capital raw bytes lost")
            require(client.ping() == "pong", "public local ping changed")
        finally:
            client.close()
        client.close()
        require(fixture.disconnected.wait(3), "close did not release the TCP connection")
        require(fixture.connections == 1, "consumer unexpectedly opened another connection")
        require((1, 0) in fixture.offsets and (1, 2) in fixture.offsets, "directory terminal page not requested")
        evidence = {
            "status": "passed", "package_version": importlib.metadata.version("eltdx"),
            "package_path": str(installed), "python": sys.version, "platform": platform.platform(),
            "toolchain_lookup": found, "commands": fixture.commands, "directory_offsets": fixture.offsets,
            "connections": fixture.connections,
        }
    # Hash the installed distribution binaries for comparison with wheel RECORD.
    distribution = importlib.metadata.distribution("eltdx")
    evidence["native_files"] = [
        {"path": str(path), "sha256": hashlib.sha256(Path(distribution.locate_file(path)).read_bytes()).hexdigest()}
        for path in distribution.files or () if str(path).endswith((".pyd", ".so", ".dylib"))
    ]
    require(evidence["native_files"], "installed package contains no native extension")
    text = json.dumps(evidence, ensure_ascii=False, indent=2)
    if args.evidence:
        args.evidence.write_text(text + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
