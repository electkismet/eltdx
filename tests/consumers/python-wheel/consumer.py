            offset = struct.unpack_from("<I", data, 2)[0]
            self.offsets.append((market, offset))
            return directory([CODE[2:].encode("ascii"), OTHER[2:].encode("ascii")]) if market == 1 and offset == 0 else b"\x00\x00"
