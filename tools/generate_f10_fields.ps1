# Source authoring only: translate literal label dictionaries to Rust data.
# Does not import, evaluate or execute either Python module, or validate Rust.
$ErrorActionPreference = 'Stop'
$repositoryRoot = Split-Path -Parent $PSScriptRoot
$destination = Join-Path $repositoryRoot 'crates/eltdx/src/f10/fields/data.rs'
$destinationParent = Split-Path -Parent $destination
if (-not (Test-Path -LiteralPath $destinationParent)) {
    New-Item -ItemType Directory -Path $destinationParent | Out-Null
}
$output = [System.Collections.Generic.List[string]]::new()
$output.Add('// Generated by tools/generate_f10_fields.ps1 from literal Python labels.')
$output.Add('// This data preserves dictionary include/override order; no Python runtime is used.')
$output.Add('use super::Label;')
$output.Add('')
foreach ($source in @('src/eltdx/f10/fields.py', 'src/eltdx/f10/fields_mg_hk.py')) {
    $inDictionary = $false
    $skipDictionary = $false
    $currentDictionary = ''
    foreach ($line in [System.IO.File]::ReadAllLines((Join-Path $repositoryRoot $source))) {
        if ($skipDictionary) {
            if ($line -match '^\}$') { $skipDictionary = $false }
            continue
        }
        if ($line -match '^(_SCOPE_PARAM_INDEX|FIELD_LABELS)') { break }
        if (-not $inDictionary -and $line -match '^(_[A-Z_0-9]+) = \{$') {
            $currentDictionary = $Matches[1].Substring(1)
            # This single multiline note is copied explicitly by fields.rs.
            if ($currentDictionary -eq 'CASHFLOW_BANK_NOTES') { $skipDictionary = $true; continue }
            $output.Add(('pub(super) static {0}: &[Label] = &[' -f $currentDictionary))
            $inDictionary = $true
            continue
        }
        if (-not $inDictionary) { continue }
        if ($line -match '^\}$') {
            $output.Add('];')
            $output.Add('')
            $inDictionary = $false
            continue
        }
        if ($line -match '^\s*\*\*(_[A-Z_0-9]+),?\s*$') {
            $output.Add(('    Label::Include({0}),' -f $Matches[1].Substring(1)))
        } elseif ($line -match '^\s*("[^"]+"):\s*("[^"]*"),?\s*(#.*)?$') {
            $output.Add(('    Label::Pair({0}, {1}),' -f $Matches[1], $Matches[2]))
        } elseif ($line -notmatch '^\s*(#.*)?$') {
            throw ('Unsupported label source syntax in {0}: {1}' -f $currentDictionary, $line)
        }
    }
}
[System.IO.File]::WriteAllLines($destination, $output, [System.Text.UTF8Encoding]::new($false))
